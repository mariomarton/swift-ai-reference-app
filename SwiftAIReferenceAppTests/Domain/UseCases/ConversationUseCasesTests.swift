import XCTest
@testable import SwiftAIReferenceApp

final class MockConversationRepository: ConversationRepository, @unchecked Sendable {
    var conversations: [Conversation] = []
    var shouldThrowOnCreate = false
    var shouldThrowOnDelete = false
    private(set) var createdConversationIDs: [UUID] = []

    func loadConversation(id: UUID) async throws -> Conversation? {
        conversations.first { $0.id == id }
    }

    func updateConversation(_ conversation: Conversation) async throws {
        guard let index = conversations.firstIndex(where: { $0.id == conversation.id }) else {
            throw NSError(domain: "mock", code: 2)
        }
        conversations[index] = conversation
    }

    func createConversation(id: UUID, title: String?) async throws -> Conversation {
        if shouldThrowOnCreate { throw NSError(domain: "mock", code: 1) }
        let conv = Conversation(id: id, title: title)
        createdConversationIDs.append(id)
        conversations.append(conv)
        return conv
    }

    func listConversations() async throws -> [Conversation] {
        return conversations
    }

    func deleteConversation(id: UUID) async throws {
        if shouldThrowOnDelete { throw NSError(domain: "mock", code: 3) }
        conversations.removeAll { $0.id == id }
    }
}

@MainActor
final class ConversationUseCasesTests: XCTestCase {
    func testCreateConversationHappyPath() async throws {
        let repo = MockConversationRepository()
        let useCase = DefaultCreateConversationUseCase(repository: repo)
        let conversationID = UUID()

        let created = try await useCase.createConversation(id: conversationID, title: "Test")
        XCTAssertEqual(created.id, conversationID)
        XCTAssertEqual(created.title, "Test")
        XCTAssertEqual(repo.conversations.count, 1)
    }

    func testLoadConversationsReturnsList() async throws {
        let repo = MockConversationRepository()
        repo.conversations = [Conversation(title: "A"), Conversation(title: "B")]
        let useCase = DefaultLoadConversationsUseCase(repository: repo)

        let loaded = try await useCase.loadConversations()
        XCTAssertEqual(loaded.count, 2)
    }

    func testCreateThrowsPropagates() async throws {
        let repo = MockConversationRepository()
        repo.shouldThrowOnCreate = true
        let useCase = DefaultCreateConversationUseCase(repository: repo)

        do {
            _ = try await useCase.createConversation(id: UUID(), title: "x")
            XCTFail("Expected throw")
        } catch {
        }
    }

    func testRenameConversationTrimsWhitespaceAndMarksItManual() async throws {
        let repo = MockConversationRepository()
        let conversation = Conversation(title: "Auto", titleOrigin: .autoGenerated)
        repo.conversations = [conversation]
        let useCase = DefaultRenameConversationUseCase(repository: repo)

        let renamed = try await useCase.renameConversation(id: conversation.id, title: "  New title  ")

        XCTAssertEqual(renamed.title, "New title")
        XCTAssertEqual(renamed.titleOrigin, .manual)
        XCTAssertEqual(repo.conversations.first?.title, "New title")
        XCTAssertEqual(repo.conversations.first?.titleOrigin, .manual)
    }

    func testRenameConversationRejectsBlankTitles() async throws {
        let repo = MockConversationRepository()
        let conversation = Conversation(title: "Existing")
        repo.conversations = [conversation]
        let useCase = DefaultRenameConversationUseCase(repository: repo)

        do {
            _ = try await useCase.renameConversation(id: conversation.id, title: "   ")
            XCTFail("Expected invalid conversation title error")
        } catch let error as DomainError {
            guard case .invalidConversationTitle = error else {
                XCTFail("Wrong DomainError case: \(error)")
                return
            }
        } catch {
            XCTFail("Unexpected error: \(error)")
        }

        XCTAssertEqual(repo.conversations.first?.title, "Existing")
    }

    func testRenameConversationMissingConversationThrowsNotFound() async throws {
        let repo = MockConversationRepository()
        let useCase = DefaultRenameConversationUseCase(repository: repo)

        do {
            _ = try await useCase.renameConversation(id: UUID(), title: "New title")
            XCTFail("Expected conversation not found error")
        } catch let error as DomainError {
            guard case .conversationNotFound = error else {
                XCTFail("Wrong DomainError case: \(error)")
                return
            }
        } catch {
            XCTFail("Unexpected error: \(error)")
        }
    }

    // MARK: - Delete

    func testDeleteConversationRemovesItFromRepository() async throws {
        let conversationRepo = MockConversationRepository()
        let messageRepo = RepoMockForLoad()
        let toDelete = Conversation(title: "To delete")
        conversationRepo.conversations = [toDelete, Conversation(title: "Keep")]

        let useCase = DefaultDeleteConversationUseCase(
            conversationRepository: conversationRepo,
            messageRepository: messageRepo
        )

        try await useCase.deleteConversation(id: toDelete.id)

        XCTAssertFalse(conversationRepo.conversations.contains(where: { $0.id == toDelete.id }))
        XCTAssertEqual(conversationRepo.conversations.count, 1)
    }

    func testDeleteConversationAlsoDeletesMessages() async throws {
        let conversationRepo = MockConversationRepository()
        let messageRepo = RepoMockForLoad()
        let conv = Conversation(title: "Chat")
        conversationRepo.conversations = [conv]
        messageRepo.stored[conv.id] = [Message(role: .user, text: "hi")]

        let useCase = DefaultDeleteConversationUseCase(
            conversationRepository: conversationRepo,
            messageRepository: messageRepo
        )

        try await useCase.deleteConversation(id: conv.id)

        XCTAssertNil(messageRepo.stored[conv.id])
        XCTAssertTrue(conversationRepo.conversations.isEmpty)
    }

    func testDeleteConversationWrapsDomainError() async throws {
        let conversationRepo = MockConversationRepository()
        let messageRepo = RepoMockForLoad()
        let conv = Conversation(title: "Will fail")
        conversationRepo.conversations = [conv]
        conversationRepo.shouldThrowOnDelete = true

        let useCase = DefaultDeleteConversationUseCase(
            conversationRepository: conversationRepo,
            messageRepository: messageRepo
        )

        do {
            try await useCase.deleteConversation(id: conv.id)
            XCTFail("Expected DomainError")
        } catch let err as DomainError {
            guard case .repositoryError = err else {
                XCTFail("Wrong domain error case: \(err)")
                return
            }
        } catch {
            XCTFail("Unexpected error: \(error)")
        }
    }
}
