import XCTest
@testable import SwiftAIReferenceApp

private enum GeneratorStubError: Error {
    case failed
}

private final class MockConversationTitleGenerator: ConversationTitleGenerator {
    var generatedTitle: String?
    var shouldThrow = false
    private(set) var invocationCount = 0
    private(set) var capturedMessages: [[Message]] = []

    func generateTitle(fromConversationMessages messages: [Message], model: LLMModel?) async throws -> String? {
        invocationCount += 1
        capturedMessages.append(messages)
        if shouldThrow {
            throw GeneratorStubError.failed
        }
        return generatedTitle
    }
}

@MainActor
final class GenerateConversationTitleUseCaseTests: XCTestCase {
    func testReturnsNilWhenExistingTitleIsUserManaged() async {
        let generator = MockConversationTitleGenerator()
        generator.generatedTitle = "Ignored"
        let useCase = DefaultGenerateConversationTitleUseCase(generator: generator)

        let result = await useCase.generateTitle(
            existingTitle: "Manual title",
            titleOrigin: .manual,
            conversationMessages: [Message(role: .user, text: "Ako funguje daň v s.r.o.?")],
            model: nil
        )

        XCTAssertNil(result)
        XCTAssertEqual(generator.invocationCount, 0)
    }

    func testRefreshesAutoGeneratedTitlesUsingRecentContext() async {
        let generator = MockConversationTitleGenerator()
        generator.generatedTitle = "dph povinnosti pre s.r.o."
        let useCase = DefaultGenerateConversationTitleUseCase(generator: generator)

        let messages = [
            Message(role: .user, text: "Topic 1"),
            Message(role: .assistant, text: "Reply 1"),
            Message(role: .user, text: "Topic 2"),
            Message(role: .assistant, text: "Reply 2"),
            Message(role: .user, text: "Topic 3"),
            Message(role: .assistant, text: "Reply 3"),
            Message(role: .user, text: "Topic 4")
        ]

        let result = await useCase.generateTitle(
            existingTitle: "Old title",
            titleOrigin: .autoGenerated,
            conversationMessages: messages,
            model: nil
        )

        XCTAssertEqual(result, "Dph povinnosti pre s.r.o.")
        XCTAssertEqual(generator.invocationCount, 1)
        XCTAssertEqual(generator.capturedMessages.count, 1)
        XCTAssertEqual(generator.capturedMessages[0].count, DefaultGenerateConversationTitleUseCase.maxContextMessages)
        XCTAssertEqual(generator.capturedMessages[0].first?.text, "Reply 1")
        XCTAssertEqual(generator.capturedMessages[0].last?.text, "Topic 4")
    }

    func testNormalizesGeneratedTitle() async {
        let generator = MockConversationTitleGenerator()
        generator.generatedTitle = "  \"  dph\n povinnosti pre   s.r.o.  \"  "
        let useCase = DefaultGenerateConversationTitleUseCase(generator: generator)

        let result = await useCase.generateTitle(
            existingTitle: nil,
            titleOrigin: .manual,
            conversationMessages: [Message(role: .user, text: "Ahoj")],
            model: nil
        )

        XCTAssertEqual(result, "Dph povinnosti pre s.r.o.")
    }

    func testFallsBackToLatestUserSentenceWhenGeneratorThrows() async {
        let generator = MockConversationTitleGenerator()
        generator.shouldThrow = true
        let useCase = DefaultGenerateConversationTitleUseCase(generator: generator)

        let result = await useCase.generateTitle(
            existingTitle: nil,
            titleOrigin: .manual,
            conversationMessages: [
                Message(role: .user, text: "Prvý dotaz"),
                Message(role: .assistant, text: "Odpoveď"),
                Message(role: .user, text: "Potrebujem poradit s danou. Co mam podat najskor?")
            ],
            model: nil
        )

        XCTAssertEqual(result, "Potrebujem poradit s danou.")
        XCTAssertEqual(generator.invocationCount, 1)
    }

    func testFallsBackToFirstNonEmptyLineWhenNoSentenceBoundary() async {
        let generator = MockConversationTitleGenerator()
        generator.generatedTitle = "   "
        let useCase = DefaultGenerateConversationTitleUseCase(generator: generator)

        let result = await useCase.generateTitle(
            existingTitle: nil,
            titleOrigin: .manual,
            conversationMessages: [
                Message(role: .user, text: "Prvý dotaz"),
                Message(role: .assistant, text: "Odpoveď"),
                Message(role: .user, text: "\n\nRozpis odvodov pre SZCO\nDruhy riadok")
            ],
            model: nil
        )

        XCTAssertEqual(result, "Rozpis odvodov pre SZCO")
    }

    func testClipsToFortyFiveCharacters() async {
        let generator = MockConversationTitleGenerator()
        generator.generatedTitle = "toto je velmi dlhy nazov konverzacie, ktory ma byt skrateny na limit"
        let useCase = DefaultGenerateConversationTitleUseCase(generator: generator)

        let result = await useCase.generateTitle(
            existingTitle: nil,
            titleOrigin: .manual,
            conversationMessages: [Message(role: .user, text: "Ahoj")],
            model: nil
        )

        XCTAssertNotNil(result)
        XCTAssertLessThanOrEqual(result?.count ?? 0, DefaultGenerateConversationTitleUseCase.maxTitleLength)
        XCTAssertEqual(result, "Toto je velmi dlhy nazov konverzacie, ktory")
    }

    func testReturnsNilWhenConversationMessagesAreBlank() async {
        let generator = MockConversationTitleGenerator()
        generator.generatedTitle = "X"
        let useCase = DefaultGenerateConversationTitleUseCase(generator: generator)

        let result = await useCase.generateTitle(
            existingTitle: nil,
            titleOrigin: .manual,
            conversationMessages: [
                Message(role: .user, text: "   \n\n   "),
                Message(role: .assistant, text: "  ")
            ],
            model: nil
        )

        XCTAssertNil(result)
        XCTAssertEqual(generator.invocationCount, 0)
    }
}
