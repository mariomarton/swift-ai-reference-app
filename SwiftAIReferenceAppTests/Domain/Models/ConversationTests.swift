import XCTest
@testable import SwiftAIReferenceApp

final class ConversationTests: XCTestCase {
    func testConversationAppendUpdatesLastMessageAndMessageCount() {
        var conv = Conversation(title: "Test")
        let msg = Message(role: .user, text: "Hello")
        conv.append(msg)

        XCTAssertEqual(conv.lastMessage, msg)
        XCTAssertEqual(conv.messages.count, 1)
    }

    func testConversationRenameMarksTitleAsManual() {
        var conv = Conversation(title: "Auto", titleOrigin: .autoGenerated)

        conv.rename(to: "Manual title")

        XCTAssertEqual(conv.title, "Manual title")
        XCTAssertEqual(conv.titleOrigin, .manual)
    }
}
