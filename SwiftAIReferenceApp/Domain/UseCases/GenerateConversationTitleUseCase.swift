import Foundation

public protocol GenerateConversationTitleUseCase {
    /// Returns a normalized title, or nil when the conversation should keep its current title.
    /// User-managed titles are never overwritten.
    func generateTitle(
        existingTitle: String?,
        titleOrigin: ConversationTitleOrigin,
        conversationMessages: [Message],
        model: LLMModel?
    ) async -> String?
}

public final class DefaultGenerateConversationTitleUseCase: GenerateConversationTitleUseCase {
    public static let maxTitleLength = 45
    public static let maxContextMessages = 6

    private let generator: ConversationTitleGenerator

    public init(generator: ConversationTitleGenerator) {
        self.generator = generator
    }

    public func generateTitle(
        existingTitle: String?,
        titleOrigin: ConversationTitleOrigin,
        conversationMessages: [Message],
        model: LLMModel?
    ) async -> String? {
        guard shouldGenerate(existingTitle: existingTitle, titleOrigin: titleOrigin, messages: conversationMessages) else {
            return nil
        }

        let recentMessages = Self.recentConversationMessages(from: conversationMessages)
        guard !recentMessages.isEmpty else {
            return nil
        }

        do {
            let generated = try await generator.generateTitle(fromConversationMessages: recentMessages, model: model)
            if let validGenerated = Self.normalizeOutput(generated) {
                return validGenerated
            }
        } catch {
            // Intentionally ignored. We always attempt deterministic fallback.
        }

        return Self.fallbackTitle(from: recentMessages)
    }

    private func shouldGenerate(
        existingTitle: String?,
        titleOrigin: ConversationTitleOrigin,
        messages: [Message]
    ) -> Bool {
        guard Self.hasNonEmptyContent(in: messages) else {
            return false
        }

        if Self.hasNonEmptyTitle(existingTitle), titleOrigin != .autoGenerated {
            return false
        }

        return true
    }

    private static func hasNonEmptyTitle(_ title: String?) -> Bool {
        guard let title else { return false }
        return !title.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }

    private static func hasNonEmptyContent(in messages: [Message]) -> Bool {
        messages.contains { !$0.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
    }

    private static func recentConversationMessages(from messages: [Message]) -> [Message] {
        let filtered = messages.filter { $0.role != .system && !$0.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty }
        guard filtered.count > maxContextMessages else {
            return filtered
        }

        return Array(filtered.suffix(maxContextMessages))
    }

    private static func normalizeOutput(_ text: String?) -> String? {
        guard let text else { return nil }

        var normalized = text
            .replacingOccurrences(of: "\n", with: " ")
            .replacingOccurrences(of: "\r", with: " ")
            .trimmingCharacters(in: .whitespacesAndNewlines)

        normalized = stripWrappingQuotes(from: normalized)
        normalized = collapseWhitespace(in: normalized)

        guard !normalized.isEmpty else {
            return nil
        }

        return capitalizedInitial(clipped(normalized, maxLength: maxTitleLength))
    }

    private static func fallbackTitle(from messages: [Message]) -> String? {
        let preferredText = latestUserMessageText(in: messages) ?? messages.last?.text
        guard let preferredText else { return nil }

        let sentence = firstSentence(from: preferredText) ?? firstNonEmptyLine(from: preferredText)
        guard let sentence else { return nil }

        let normalized = normalizeOutput(sentence)
        return normalized
    }

    private static func latestUserMessageText(in messages: [Message]) -> String? {
        for message in messages.reversed() where message.role == .user {
            let normalized = message.text.trimmingCharacters(in: .whitespacesAndNewlines)
            if !normalized.isEmpty {
                return normalized
            }
        }

        return nil
    }

    private static func firstSentence(from text: String) -> String? {
        let scalars = Array(text)
        guard !scalars.isEmpty else { return nil }

        for idx in scalars.indices {
            let char = scalars[idx]
            if char == "." || char == "!" || char == "?" {
                let candidate = String(scalars[...idx])
                let normalized = collapseWhitespace(in: candidate).trimmingCharacters(in: .whitespacesAndNewlines)
                if !normalized.isEmpty {
                    return normalized
                }
            }
        }

        return nil
    }

    private static func firstNonEmptyLine(from text: String) -> String? {
        for line in text.components(separatedBy: .newlines) {
            let normalized = collapseWhitespace(in: line).trimmingCharacters(in: .whitespacesAndNewlines)
            if !normalized.isEmpty {
                return normalized
            }
        }

        return nil
    }

    private static func stripWrappingQuotes(from text: String) -> String {
        var value = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let quotePairs: [(Character, Character)] = [
            ("\"", "\""),
            ("'", "'"),
            ("„", "“"),
            ("\u{201C}", "\u{201D}")
        ]

        var removed = true
        while removed, value.count >= 2 {
            removed = false
            for pair in quotePairs {
                if value.first == pair.0, value.last == pair.1 {
                    value.removeFirst()
                    value.removeLast()
                    value = value.trimmingCharacters(in: .whitespacesAndNewlines)
                    removed = true
                    break
                }
            }
        }

        return value
    }

    private static func collapseWhitespace(in text: String) -> String {
        text
            .components(separatedBy: .whitespacesAndNewlines)
            .filter { !$0.isEmpty }
            .joined(separator: " ")
    }

    private static func clipped(_ text: String, maxLength: Int) -> String {
        guard text.count > maxLength else {
            return text
        }

        let hardCut = String(text.prefix(maxLength)).trimmingCharacters(in: .whitespacesAndNewlines)
        if let lastSpace = hardCut.lastIndex(of: " "), lastSpace != hardCut.startIndex {
            let candidate = hardCut[..<lastSpace].trimmingCharacters(in: .whitespacesAndNewlines)
            if !candidate.isEmpty {
                return String(candidate)
            }
        }

        return hardCut
    }

    private static func capitalizedInitial(_ text: String) -> String {
        guard let first = text.first else { return text }
        return first.uppercased() + text.dropFirst()
    }
}
