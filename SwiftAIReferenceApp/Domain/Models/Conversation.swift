import Foundation

public struct Conversation: Identifiable, Codable, Equatable, Sendable {
    public let id: UUID
    public var title: String?
    public var titleOrigin: ConversationTitleOrigin
    public var messages: [Message]
    public var selectedModel: LLMModel?
    public let createdAt: Date
    public var updatedAt: Date

    public init(
        id: UUID = .init(),
        title: String? = nil,
        titleOrigin: ConversationTitleOrigin = .manual,
        messages: [Message] = [],
        selectedModel: LLMModel? = nil,
        createdAt: Date = .init(),
        updatedAt: Date = .init()
    ) {
        self.id = id
        self.title = title
        self.titleOrigin = titleOrigin
        self.messages = messages
        self.selectedModel = selectedModel
        self.createdAt = createdAt
        self.updatedAt = updatedAt
    }

    public mutating func append(_ message: Message) {
        messages.append(message)
        updatedAt = Date()
    }

    public mutating func rename(to title: String) {
        self.title = title
        titleOrigin = .manual
        updatedAt = Date()
    }

    public var lastMessage: Message? {
        messages.last
    }

    public var isAutoGeneratedTitle: Bool {
        titleOrigin == .autoGenerated
    }

    private enum CodingKeys: String, CodingKey {
        case id
        case title
        case titleOrigin
        case messages
        case selectedModel
        case createdAt
        case updatedAt
    }

    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        id = try container.decode(UUID.self, forKey: .id)
        title = try container.decodeIfPresent(String.self, forKey: .title)
        messages = try container.decodeIfPresent([Message].self, forKey: .messages) ?? []
        selectedModel = try container.decodeIfPresent(LLMModel.self, forKey: .selectedModel)
        createdAt = try container.decode(Date.self, forKey: .createdAt)
        updatedAt = try container.decode(Date.self, forKey: .updatedAt)

        if let decodedOrigin = try container.decodeIfPresent(ConversationTitleOrigin.self, forKey: .titleOrigin) {
            titleOrigin = decodedOrigin
        } else {
            titleOrigin = title?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty == false ? .autoGenerated : .manual
        }
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)
        try container.encode(id, forKey: .id)
        try container.encode(title, forKey: .title)
        try container.encode(titleOrigin, forKey: .titleOrigin)
        try container.encode(messages, forKey: .messages)
        try container.encode(selectedModel, forKey: .selectedModel)
        try container.encode(createdAt, forKey: .createdAt)
        try container.encode(updatedAt, forKey: .updatedAt)
    }
}
